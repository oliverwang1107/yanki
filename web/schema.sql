-- mod 一律是毫秒；Anki 匯入的秒數在 make_seed.mjs 乘上 1000。
-- 日期欄位用「學習日」編號（本機時區、凌晨 4 點換日），算法見 tools/export_anki.py。
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS notetypes (id INTEGER PRIMARY KEY, name TEXT NOT NULL, fields TEXT NOT NULL, qfmt TEXT NOT NULL, afmt TEXT NOT NULL, css TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS decks (id INTEGER PRIMARY KEY, name TEXT NOT NULL, config INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS configs (id INTEGER PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS notes (id INTEGER PRIMARY KEY, guid TEXT NOT NULL, mid INTEGER NOT NULL, mod INTEGER NOT NULL, tags TEXT NOT NULL, fields TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cards (
  id INTEGER PRIMARY KEY, nid INTEGER NOT NULL, did INTEGER NOT NULL, ord INTEGER NOT NULL,
  type INTEGER NOT NULL, queue INTEGER NOT NULL, ivl INTEGER NOT NULL, reps INTEGER NOT NULL,
  lapses INTEGER NOT NULL, left INTEGER NOT NULL DEFAULT 0, mod INTEGER NOT NULL, s REAL, d REAL, lrt INTEGER,
  pos INTEGER, due_ts INTEGER, due_day INTEGER
);
CREATE TABLE IF NOT EXISTS revlog (id INTEGER PRIMARY KEY, cid INTEGER NOT NULL, ease INTEGER NOT NULL, ivl INTEGER NOT NULL, last_ivl INTEGER NOT NULL, time INTEGER NOT NULL, type INTEGER NOT NULL);
-- 單字的「字典」內容（同義字、反義字、英文釋義…），每個 note 一列，data 是 JSON。
CREATE TABLE IF NOT EXISTS dict (id INTEGER PRIMARY KEY, mod INTEGER NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS dict_mod ON dict (mod, id);
CREATE INDEX IF NOT EXISTS notes_mod ON notes (mod, id);
CREATE INDEX IF NOT EXISTS cards_mod ON cards (mod, id);
CREATE INDEX IF NOT EXISTS revlog_cid ON revlog (cid);
